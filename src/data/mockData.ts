export const getLevelInfo = (xp: number) => {
  for (let i = LEVEL_THRESHOLDS.length - 1; i >= 0; i--) {
    if (xp >= LEVEL_THRESHOLDS[i].minXp) {
      const current = LEVEL_THRESHOLDS[i];
      const progressPercent = Math.min(
        100,
        Math.round(((xp - current.minXp) / (current.maxXp - current.minXp)) * 100)
      );
      return {
        level: current.level,
        title: current.title,
        minXp: current.minXp,
        maxXp: current.maxXp,
        progressPercent,
        nextLevelXp: current.maxXp,
      };
    }
  }
  return {
    level: 1,
    title: LEVEL_THRESHOLDS[0].title,
    minXp: 0,
    maxXp: 100,
    progressPercent: 0,
    nextLevelXp: 100,
  };
};

